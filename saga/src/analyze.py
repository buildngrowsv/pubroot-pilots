import json, collections, sys
R = [json.loads(l) for l in open("results/runs.jsonl")]
L = [json.loads(l) for l in open("results/operation_labels.jsonl")]
env = json.load(open("results/environment.json"))
out = []
P = out.append
P("# Saga pilot summary (generated by src/analyze.py from results/runs.jsonl)\n")
P(f"Environment: Python {env['python'].split()[0]}, {env['git']}, window = {env['window_ticks']} ticks. Packages: " + ", ".join(f"{k} {v}" for k, v in env['packages'].items()) + "\n")
P("## Operation labels (empirical: invert immediately, then after the window)\n")
P("| Operation | Immediate inverse | Residue | Late inverse | Label |\n|---|---|---|---|---|")
for l in L:
    P(f"| {l['op']} | {l['immediate']} | {', '.join(l.get('immediate_residue', [])) or '-'} | {l['late']} | **{l['label']}** |")
lab = {l['op']: l['label'] for l in L}
from collections import Counter
P("\nLabel counts over the 11 operations: " + ", ".join(f"{k} {v}" for k, v in Counter(lab.values()).items()))
plans = {}
for r in R:
    if r['order'] == 'original':
        plans[r['plan']] = r['plan_ops']
P("\n## Plans (original order) and labels\n")
for p, ops in plans.items():
    P(f"- {p}: " + " → ".join(f"{o} ({lab[o]})" for o in ops))
P("\n## Native framework behaviour on an injected tool exception\n")
P("| Framework | Runs | invoke raised | Mean tool executions of the faulting step | Max | Runs with duplicate effects |\n|---|---|---|---|---|---|")
for fw in ["langgraph", "ag2", "crewai"]:
    rs = [r for r in R if r['framework'] == fw and r['recovery'] == 'none']
    raised = sum(1 for r in rs if r['native']['raised'])
    ex = [r['exec_count'].get(str(r['fault_step']), 0) for r in rs]
    dup = sum(1 for r in rs if r['duplicate_effects'] > 0)
    P(f"| {fw} | {len(rs)} | {raised} | {sum(ex)/len(ex):.2f} | {max(ex)} | {dup} |")
ex_kinds = collections.Counter(r['native']['raised'].split(':')[0] for r in R if r['native']['raised'])
P(f"\nExceptions surfaced by invoke(): {dict(ex_kinds)}")
P("\n## Recovery outcomes (counts over 3 plans × 6 fault steps = 18 runs per cell)\n")
P("| Framework | Order | Fault | none: clean/residue | trace-based saga: clean/residue/stuck | effect-log saga: clean/residue/stuck |\n|---|---|---|---|---|---|")
def cnt(rs):
    c = Counter(r['outcome'] for r in rs); return c
for fw in ["langgraph", "ag2", "crewai"]:
    for order in ["original", "irreversible_last"]:
        for kind in ["pre", "post"]:
            cell = {}
            for rec in ["none", "trace", "effect_log"]:
                cell[rec] = cnt([r for r in R if r['framework'] == fw and r['order'] == order and r['fault_kind'] == kind and r['recovery'] == rec])
            P(f"| {fw} | {order} | {kind} | {cell['none']['clean']}/{cell['none']['residue']} | {cell['trace']['clean']}/{cell['trace']['residue']}/{cell['trace']['stuck']} | {cell['effect_log']['clean']}/{cell['effect_log']['residue']}/{cell['effect_log']['stuck']} |")
P("\n## Aggregates\n")
def agg(f):
    rs = [r for r in R if f(r)]; c = Counter(r['outcome'] for r in rs); n = len(rs)
    return n, c
for rec in ["trace", "effect_log"]:
    for order in ["original", "irreversible_last"]:
        n, c = agg(lambda r: r['recovery'] == rec and r['order'] == order)
        P(f"- {rec}, {order}: n={n}; clean {c['clean']} ({100*c['clean']/n:.1f}%), residue {c['residue']} ({100*c['residue']/n:.1f}%), stuck {c['stuck']} ({100*c['stuck']/n:.1f}%)")
# excluding trivial runs (nothing committed before the fault)
P("\nExcluding trivial runs where no effect was applied before recovery:")
for rec in ["trace", "effect_log"]:
    for order in ["original", "irreversible_last"]:
        n, c = agg(lambda r: r['recovery'] == rec and r['order'] == order and r['effect_steps'])
        P(f"- {rec}, {order}: n={n}; clean {c['clean']} ({100*c['clean']/n:.1f}%), residue {c['residue']}, stuck {c['stuck']} ({100*c['stuck']/n:.1f}%)")
post = [r for r in R if r['fault_kind'] == 'post' and r['recovery'] == 'trace']
miss = sum(1 for r in post if r['untracked_effects'])
P(f"\nPost-effect faults: the framework trace omitted an applied effect in {miss}/{len(post)} runs (trace-based recovery).")
for fw in ["langgraph", "ag2", "crewai"]:
    rs = [r for r in post if r['framework'] == fw]
    P(f"- {fw}: {sum(1 for r in rs if r['untracked_effects'])}/{len(rs)}")
resid = Counter(k for r in R if r['recovery'] == 'effect_log' for k in r['residue'])
P(f"\nResidue fields after effect-log recovery (all runs): {dict(resid.most_common())}")
comp = Counter(c['result'].split(':')[0] for r in R if r['recovery'] in ('trace', 'effect_log') for c in r['compensation'])
P(f"\nCompensation action results (trace + effect-log runs): {dict(comp)}")
wc = Counter((c['op']) for r in R if r['recovery'] in ('trace','effect_log') for c in r['compensation'] if c['result']=='window_closed')
P(f"Window-closed inverses by operation: {dict(wc)}")
open("results/summary.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))
